use crate::error::{LibraryError, Result};
use specimen_core::{Config, ItemType};
use std::fs;
use std::path::{Path, PathBuf};

pub struct InitSummary {
    pub root: PathBuf,
    pub created_dirs: Vec<PathBuf>,
    pub created_files: Vec<PathBuf>,
}

const COLLECTION_TYPES: &[ItemType] = &[
    ItemType::Icon,
    ItemType::Palette,
    ItemType::Typography,
    ItemType::Theme,
    ItemType::Layout,
    ItemType::Effect,
    ItemType::Animation,
    ItemType::Component,
];

/// Initializes a new Specimen design library adhering to SPEC §3.
pub fn init_library(target_dir: &Path, name: Option<&str>) -> Result<InitSummary> {
    if !target_dir.exists() {
        fs::create_dir_all(target_dir)?;
    }

    let config_file = target_dir.join("specimen.toml");
    if config_file.exists() {
        return Err(LibraryError::AlreadyInitialized(
            target_dir.display().to_string(),
        ));
    }

    let mut created_dirs = Vec::new();
    let mut created_files = Vec::new();

    // 1. Directory layout: sources, collections, exports
    let sources_dir = target_dir.join("sources");
    fs::create_dir_all(&sources_dir)?;
    created_dirs.push(sources_dir);

    let exports_dir = target_dir.join("exports");
    fs::create_dir_all(&exports_dir)?;
    created_dirs.push(exports_dir);

    let collections_dir = target_dir.join("collections");
    for item_type in COLLECTION_TYPES {
        let type_dir = collections_dir.join(item_type.collection_dir_name());
        fs::create_dir_all(&type_dir)?;
        created_dirs.push(type_dir);
    }

    // 2. Write specimen.toml
    let mut config = Config::default();
    if let Some(custom_name) = name {
        config.library.name = custom_name.to_string();
    }
    config.library.notice_acknowledged = true;
    let config_str = toml::to_string_pretty(&config)?;
    fs::write(&config_file, config_str)?;
    created_files.push(config_file);

    // 3. Write .gitignore
    let gitignore_file = target_dir.join(".gitignore");
    let gitignore_content =
        "# Generated by Specimen\n.cache/\nassets-restricted/\n*.tmp\n*.partial\n";
    fs::write(&gitignore_file, gitignore_content)?;
    created_files.push(gitignore_file);

    // 4. Write README.md
    let readme_file = target_dir.join("README.md");
    let lib_title = name.unwrap_or("Design Library");
    let readme_content = format!(
        "# {}\n\nPersonal design system library managed by [Specimen](https://github.com/specimen-design/specimen).\n\n## Collections\n\n- `collections/icons/`\n- `collections/palettes/`\n- `collections/typography/`\n- `collections/themes/`\n- `collections/layouts/`\n- `collections/effects/`\n- `collections/animations/`\n- `collections/components/`\n",
        lib_title
    );
    fs::write(&readme_file, readme_content)?;
    created_files.push(readme_file);

    Ok(InitSummary {
        root: target_dir.to_path_buf(),
        created_dirs,
        created_files,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_init_library_success() {
        let temp = tempfile::tempdir().unwrap();
        let lib_path = temp.path().join("my-library");
        let summary = init_library(&lib_path, Some("Brand Specimen")).unwrap();

        assert!(lib_path.join("specimen.toml").exists());
        assert!(lib_path.join(".gitignore").exists());
        assert!(lib_path.join("README.md").exists());
        assert!(lib_path.join("sources").exists());
        assert!(lib_path.join("exports").exists());
        assert!(lib_path.join("collections/palettes").exists());
        assert!(lib_path.join("collections/icons").exists());
        assert_eq!(summary.created_files.len(), 3);

        // Cannot re-init existing
        assert!(init_library(&lib_path, None).is_err());
    }
}
